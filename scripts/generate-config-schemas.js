// Extracts the per-widget-type config schemas from src/schema.json into src/utils/widget-config-schemas.ts, which
// the report builder's default configuration panel is generated from. Run after changing schema.json:
//   npm run generate:config-schemas
const fs = require('fs');
const path = require('path');

const schema = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'src', 'schema.json'), 'utf8'));
const definitions = schema.definitions;
const types = definitions.Widget.properties.type.enum;
const refs = definitions.Widget.properties.config.oneOf.map(entry => entry.$ref.split('/').pop());

// Widget types map to their config definition by name, except where the casing differs
const overrides = { WelchANOVA: 'WelchAnovaWidgetConfig', oneWayANOVA: 'OneWayAnovaWidgetConfig', data: 'DataWidgetConfig' };

const result = {};
types.forEach(type => {
  const name = overrides[type] || type.charAt(0).toUpperCase() + type.slice(1) + 'WidgetConfig';
  if (!definitions[name]) throw new Error(`No config definition ${name} for widget type ${type}`);
  if (!refs.includes(name)) console.warn(`${name} is not in Widget.config.oneOf`);
  result[type] = definitions[name];
});

const out = `// Generated by scripts/generate-config-schemas.js from src/schema.json. Do not edit.
export const BUILT_IN_CONFIG_SCHEMAS: Record<string, any> = ${JSON.stringify(result)};
`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'utils', 'widget-config-schemas.ts'), out);
console.log(`Wrote ${types.length} schemas (${out.length} bytes)`);
